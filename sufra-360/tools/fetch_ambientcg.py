"""Download CC0 scanned PBR material sets from ambientCG and install them.

The venue's outdoor surfaces were procedural: the "grass" was the gravel
texture with a green tint on it, the pavement and the plaster were generated by
tools/texture_gen.py. Scanned photography is the single biggest realism jump
available for large flat areas, and ambientCG is CC0 with no account and no
CAPTCHA.

    python3 tools/fetch_ambientcg.py            # everything in WANTED
    python3 tools/fetch_ambientcg.py Grass004   # one set

Writes static/3d/textures/<local>_albedo.jpg / _normal.jpg / _rough.jpg, which
is the naming AssetManager.pbr() already expects. Downloads go through curl:
python.org's interpreter ships without a CA bundle on this machine.
"""
import io
import pathlib
import subprocess
import sys
import zipfile

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "static" / "3d" / "textures"
CACHE = ROOT / "assets_src" / "ambientcg"

# local name -> (ambientCG asset id, size to ship, note for ASSET_CREDITS.md)
# 1K source, shipped at 1024 for ground the camera stands on and 512 for the
# far parkland, which is never seen closer than 58 m.
WANTED = {
    "grass":     ("Grass004", 1024, "the parkland and the garden lawn"),
    "paving":    ("PavingStones131", 1024, "the promenade and the quay walk"),
    "concrete":  ("Concrete042A", 1024, "the kerb, the quay face and the apron"),
    "stucco":    ("Plaster001", 1024, "the building's rendered walls"),
}

MAPS = {"albedo": "_Color", "normal": "_NormalGL", "rough": "_Roughness"}


def fetch(asset_id):
    CACHE.mkdir(parents=True, exist_ok=True)
    zpath = CACHE / f"{asset_id}_1K-JPG.zip"
    if zpath.exists() and zpath.stat().st_size > 10000:
        return zpath
    url = f"https://ambientcg.com/get?file={asset_id}_1K-JPG.zip"
    print(f"  downloading {url}")
    r = subprocess.run(["curl", "-sL", "-o", str(zpath), url], capture_output=True)
    if r.returncode != 0 or not zpath.exists() or zpath.stat().st_size < 10000:
        raise RuntimeError(f"{asset_id}: download failed")
    return zpath


def install(local, asset_id, size):
    zpath = fetch(asset_id)
    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    with zipfile.ZipFile(zpath) as z:
        names = z.namelist()
        for out_suffix, acg_suffix in MAPS.items():
            hit = next((n for n in names if n.endswith(acg_suffix + ".jpg")), None)
            if hit is None:
                print(f"  !! {asset_id} has no {acg_suffix}", file=sys.stderr)
                continue
            im = Image.open(io.BytesIO(z.read(hit))).convert("RGB")
            if max(im.size) > size:
                im = im.resize((size, size), Image.LANCZOS)
            dest = OUT / f"{local}_{out_suffix}.jpg"
            # quality 88: these tile across hundreds of square metres, and the
            # difference between 88 and 95 is 40% more bytes for no visible gain
            im.save(dest, "JPEG", quality=88, optimize=True)
            written.append((dest.name, dest.stat().st_size))
    for name, n in written:
        print(f"  {name:24} {n / 1e6:5.2f} MB")
    return written


def main():
    only = sys.argv[1:]
    for local, (asset_id, size, note) in WANTED.items():
        if only and asset_id not in only and local not in only:
            continue
        print(f"{local}  <-  ambientCG {asset_id}  ({note})")
        try:
            install(local, asset_id, size)
        except Exception as e:
            print(f"  !! {e}", file=sys.stderr)


if __name__ == "__main__":
    main()
